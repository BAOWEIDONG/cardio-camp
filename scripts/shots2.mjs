import { chromium } from 'playwright';
import fs from 'fs';
const BASE = 'http://localhost:4173/cardio-camp/';
const OUT = '/sessions/admiring-pensive-darwin/mnt/outputs/cardio-camp-shots';
const browser = await chromium.launch({ headless: true });
const ctx = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true });
const page = await ctx.newPage();
page.on('pageerror', (e) => console.log('PAGEERROR:', e.message));
await page.goto(BASE, { waitUntil: 'networkidle' });
await page.evaluate(() => localStorage.clear());
await page.reload({ waitUntil: 'networkidle' });
await page.waitForTimeout(500);
await page.locator('button', { hasText: '学员' }).first().click();
await page.locator('.van-checkbox').click();
await page.getByText('一键进入演示').click();
await page.waitForTimeout(2600);
await page.screenshot({ path: `${OUT}/20-home-aligned.png` });
await page.getByText('家庭血压').first().click();
await page.waitForTimeout(600);
await page.screenshot({ path: `${OUT}/21-bp-standalone.png` });
await page.goBack(); await page.waitForTimeout(500);
await page.getByText('个人历程').first().click();
await page.waitForTimeout(600);
await page.screenshot({ path: `${OUT}/22-journey.png` });
await page.goBack(); await page.waitForTimeout(500);
await page.getByText('我的奖励').first().click();
await page.waitForTimeout(600);
await page.screenshot({ path: `${OUT}/23-rewards.png` });
await page.goBack(); await page.waitForTimeout(500);
await page.getByText('活动', { exact: true }).last().click();
await page.waitForTimeout(600);
await page.screenshot({ path: `${OUT}/24-activity-hub.png` });
await browser.close();
console.log('done');
